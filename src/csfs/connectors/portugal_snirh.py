"""Portugal SNIRH connector — Sistema Nacional de Informação de Recursos Hídricos.

SNIRH (snirh.apambiente.pt), operated by the Agência Portuguesa do Ambiente
(APA), publishes historical daily-mean discharge and stage for ~700 hydrometric
stations. Data are served by a legacy PHP endpoint that renders one HTML table
per request:

    GET /snirh/_dadosbase/site/janela_verdados.php
        ?sites=<numeric_site_id>&pars=<param_id>&tmin=DD/MM/YYYY&tmax=DD/MM/YYYY

with parameter 1850 = "Caudal médio diário" (daily-mean discharge, m3/s) and
1845 = "Nível médio diário" (daily-mean stage, m).

CRITICAL QUIRK: the server ignores ``tmin``/``tmax`` and always returns the
FULL period of record, so this connector filters rows client-side. A station
with no record for a parameter returns a "Sem dados." page instead of a table.

The ``sites`` parameter takes SNIRH-internal numeric ids (e.g. 1627743378),
not the human station codes (e.g. "19B/01H"). SNIRH exposes no scriptable
public station-list endpoint (the station-network pages are session-driven
JavaScript), so this connector bundles a seed catalogue of 715 gauges —
station code, numeric site id, WGS84 coordinates — data collated from SNIRH's
own network listing by the RivRetrieve project (facts only; independent
implementation). Three gauges with corrupt upstream coordinates are excluded.

Operational note: the SNIRH edge returns a bare ``403 Forbidden`` for entire
(apparently non-Portuguese) IP ranges — if every request 403s, it is an
IP-level block, not a header problem. Response markup was verified against
archived responses for four distinct stations and both "data" and "Sem dados."
page shapes (Wayback Machine captures 2021-2025 plus a 2025-10 capture of
station 19B/01H stage data).

References
----------
- Portal: https://snirh.apambiente.pt/
- Route + quirks cross-checked against RivRetrieve-Python's Portugal fetcher.
"""

from __future__ import annotations

import re
from datetime import UTC, datetime

import structlog

from csfs.connectors.base import BaseConnector
from csfs.core.models import (
    Observation,
    QualityFlag,
    Resolution,
    Station,
    TimeSeriesChunk,
    Variable,
)
from csfs.core.registry import register

logger = structlog.get_logger()

_SNIRH_BASE_URL = "https://snirh.apambiente.pt"
_DATA_PATH = "/snirh/_dadosbase/site/janela_verdados.php"

#: SNIRH parameter ids for the daily-mean series this connector ingests.
_PARAM_DISCHARGE = "1850"  # Caudal médio diário (m3/s)
_PARAM_STAGE = "1845"  # Nível médio diário (m)

#: Marker of the (valid) "no record for this parameter" response page.
_NO_DATA_MARKER = "Sem dados"
#: CSS class present on every data-table header cell — used to recognise that
#: a response is structurally a SNIRH data page even when it has zero rows.
_TABLE_MARKER = "tbl_tit"

# One data row of the rendered table:
#   <td nowrap="nowrap" align="center" class="tbl_val">16/02/2002 00:00</td>
#   <td align="right" class="tbl_val">
#       0.36 </td>
# The value cell wraps its content in tabs/newlines; it never contains markup.
_ROW_RE = re.compile(
    r'class="tbl_val">\s*(?P<ts>\d{2}/\d{2}/\d{4}\s+\d{2}:\d{2})\s*</td>\s*'
    r'<td[^>]*class="tbl_val">\s*(?P<val>[^<]*?)\s*</td>',
    re.DOTALL,
)
_NUM_RE = re.compile(r"[-+]?\d+(?:\.\d+)?")


@register("portugal_snirh")
class PortugalSnirhConnector(BaseConnector):
    """Connector for Portugal's SNIRH daily discharge and stage archive."""

    slug = "portugal_snirh"
    display_name = "SNIRH (Portugal)"
    base_url = _SNIRH_BASE_URL
    country_codes = ["PT"]
    supported_variables = ("discharge", "stage")

    async def __aenter__(self) -> PortugalSnirhConnector:
        await super().__aenter__()
        # The SNIRH portal sends browser-family UA + Referer with data
        # requests; mirror that (the site's own JS windows do the same).
        self.client.headers.update({
            "User-Agent": "Mozilla/5.0 (compatible; CSFS/0.1; +https://github.com/DarriEy/CSFS)",
            "Referer": "https://snirh.apambiente.pt/",
        })
        return self

    async def fetch_stations(self) -> list[Station]:
        """Return the bundled seed catalogue (no scriptable live endpoint)."""
        stations = [
            Station(
                id=self._station_id(code),
                provider=self.slug,
                native_id=code,
                name=code,
                latitude=lat,
                longitude=lon,
                country_code="PT",
            )
            for code, (_, lat, lon) in sorted(_seed_catalog().items())
        ]
        logger.info("stations_fetched", provider=self.slug, count=len(stations))
        return stations

    async def fetch_observations(
        self,
        station_id: str,
        start: datetime,
        end: datetime,
    ) -> TimeSeriesChunk:
        """Fetch daily-mean discharge and stage, windowed client-side.

        The server ignores ``tmin``/``tmax`` and returns the full record, so
        the [start, end] filter is applied here. Stage is only requested when
        the discharge request succeeded structurally, to avoid double-failing
        against a blocked or broken host.
        """
        native_id = station_id.removeprefix(f"{self.slug}:")
        site = self._numeric_site_id(native_id)
        if site is None:
            logger.warning("snirh_unknown_station", provider=self.slug, station=native_id)
            return self._chunk(station_id, [])

        observations: list[Observation] = []
        tmax = datetime.now(UTC).strftime("%d/%m/%Y")
        for par, variable in (
            (_PARAM_DISCHARGE, Variable.DISCHARGE),
            (_PARAM_STAGE, Variable.STAGE),
        ):
            try:
                resp = await self._get(
                    _DATA_PATH,
                    params={"sites": site, "pars": par, "tmin": "01/01/1900", "tmax": tmax},
                )
            except Exception as exc:  # noqa: BLE001 - degrade gracefully; host geo-blocks some ranges
                logger.warning(
                    "snirh_fetch_failed",
                    provider=self.slug, station=native_id, par=par,
                    error_type=type(exc).__name__, error=str(exc)[:160],
                )
                if variable is Variable.DISCHARGE:
                    break  # structural failure: don't double-fail on stage
                continue

            html = resp.text
            rows = _parse_table(html)
            if not rows and _NO_DATA_MARKER not in html and _TABLE_MARKER not in html:
                # Not a SNIRH data page at all (edge/WAF interstitial, etc.).
                logger.warning(
                    "snirh_unexpected_response",
                    provider=self.slug, station=native_id, par=par, size=len(html),
                )
                if variable is Variable.DISCHARGE:
                    break
                continue

            observations.extend(
                Observation(
                    station_id=station_id,
                    timestamp=ts,
                    variable=variable,
                    resolution=Resolution.DAILY_MEAN,
                    value=value,
                    quality=QualityFlag.RAW,
                )
                for ts, value in rows
                if start <= ts <= end
            )

        return self._chunk(station_id, observations)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _numeric_site_id(self, native_id: str) -> str | None:
        """Map a station code (e.g. '19B/01H') to its SNIRH numeric site id."""
        entry = _seed_catalog().get(native_id)
        if entry is not None:
            return entry[0]
        if native_id.isdigit():  # allow passing a raw SNIRH numeric id
            return native_id
        return None

    def _chunk(self, station_id: str, observations: list[Observation]) -> TimeSeriesChunk:
        return TimeSeriesChunk(
            station_id=station_id,
            provider=self.slug,
            observations=observations,
            fetched_at=datetime.now(UTC),
        )


def _parse_table(html: str) -> list[tuple[datetime, float]]:
    """Extract (timestamp, value) pairs from a janela_verdados HTML table.

    Daily-mean rows are stamped ``DD/MM/YYYY 00:00``; timestamps are returned
    tz-aware UTC. Cells that hold no parseable number are skipped.
    """
    rows: list[tuple[datetime, float]] = []
    for m in _ROW_RE.finditer(html):
        try:
            ts = datetime.strptime(m.group("ts"), "%d/%m/%Y %H:%M").replace(tzinfo=UTC)
        except ValueError:
            continue
        raw = m.group("val").strip()
        try:
            value = float(raw)
        except ValueError:
            num = _NUM_RE.search(raw)
            if num is None:
                continue
            value = float(num.group())
        rows.append((ts, value))
    return rows


_catalog_cache: dict[str, tuple[str, float, float]] | None = None


def _seed_catalog() -> dict[str, tuple[str, float, float]]:
    """station code -> (numeric SNIRH site id, latitude, longitude)."""
    global _catalog_cache
    if _catalog_cache is None:
        catalog: dict[str, tuple[str, float, float]] = {}
        for line in _SEED_CATALOG.strip().splitlines():
            code, num_id, lat, lon = line.split(",")
            catalog[code] = (num_id, float(lat), float(lon))
        _catalog_cache = catalog
    return _catalog_cache


